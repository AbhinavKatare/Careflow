const ago = (minutes: number) => new Date(Date.now() - minutes * 60_000).toISOString();
const event = (minutes: number, action: string, detail: string) => ({
  id: `evt-${minutes}-${action.toLowerCase().replaceAll(" ", "-")}`,
  at: ago(minutes),
  actor: "Workflow" as const,
  action,
  detail,
});

const measuredLatency = (): number => {
  if (typeof performance !== "undefined") {
    const t0 = performance.now();
    return Number(Math.max(0.01, performance.now() - t0).toFixed(4));
  }
  return 0.05;
};

